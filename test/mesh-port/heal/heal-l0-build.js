#!/usr/bin/env node
// heal-l0-build.js <sim dir> <out dir>
// Builds the heal L0 driver: heal-l0-driver.cpp compiled against the sim's own topo.h and the sim's own text of
// the pure functions of mesh_heal.inc (rmWitCells, l13Ring, l13Witness, l13Chain, l13Line) and ownerCoordOf (mesh_seat.inc),
// each cut from the sim source by name. Nothing is retyped. Prints the binary's path.
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');
const [simDir, outDir] = process.argv.slice(2);
if (!simDir || !outDir) { console.error('usage: heal-l0-build.js <sim dir> <out dir>'); process.exit(2); }
const heal = fs.readFileSync(path.join(simDir, 'mesh_heal.inc'), 'utf8').split('\n');
const seat = fs.readFileSync(path.join(simDir, 'mesh_seat.inc'), 'utf8').split('\n');
// the lines of one definition: from the line that starts it up to the line that ends it with a closing brace at column 0 (or the same line)
function cut(lines, re) {
  const a = lines.findIndex((l) => re.test(l)); if (a < 0) throw new Error('heal-l0-build: no ' + re);
  let b = a; if (!/\}\s*(\/\/.*|\/\*.*)?$/.test(lines[a]) || /^\s*(static )?(int|bool) \w+\([^)]*\)\s*\{\s*$/.test(lines[a])) { while (!/^\}/.test(lines[b])) b++; }
  return lines.slice(a, b + 1).join('\n');
}
const mcpp = fs.readFileSync(path.join(simDir, 'mesh.cpp'), 'utf8').split('\n');
const parts = [
  ...[/^static const uint32_t H_INIT=/, /^static inline uint32_t fmix32\(/, /^static inline uint32_t hmix\(/, /^static inline uint32_t hmix64\(/].map((re) => mcpp.find((l) => re.test(l))),   // one-line definitions (findLeaf's l9Fwd key)
  cut(seat, /^static inline bool ownerCoordOf\(/),
  cut(heal, /^static int rmWitCells\(/),
  cut(heal, /^static int l13Ring\(/),
  cut(heal, /^static bool l13Witness\(/),
  'static const int L13_CHAIN_MAX=6;',
  cut(heal, /^static int l13Chain\(/),
  cut(heal, /^static int l13Line\(/),
];
const hdr = '// GENERATED by heal-l0-build.js from the sim source: do not edit.\n#pragma once\nstatic bool L13_15=false;\nstatic bool l13(const char* sub){ (void)sub; return L13_15; }\n' + parts.join('\n') + '\n';
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'heal-l0-sim.h'), hdr);
const bin = path.join(outDir, 'heal-l0-driver');
cp.execFileSync('g++', ['-O2', '-std=c++17', '-I', simDir, '-I', outDir, '-o', bin, path.join(__dirname, 'heal-l0-driver.cpp')], { stdio: 'inherit' });
console.log(bin);
