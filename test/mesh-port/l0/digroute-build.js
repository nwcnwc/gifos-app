#!/usr/bin/env node
// digroute-build.js <sim dir> <out dir>
// Builds the digroute L0 driver: the pure functions of mesh_seat.inc (S5/S6: l12Origin/l12Score/l12Cand, kHash,
// kSameVote, kHasVote, kTakerOf, kOver, kInScope, cellOk, nextHopCoord, coordStr) cut from the sim's own text and
// compiled with the sim's headers. Nothing is retyped (only nextHopCoord's header line: the Seat member becomes a
// function of the seat's coord). Prints the binary's path.
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');
const [simDir, outDir] = process.argv.slice(2);
if (!simDir || !outDir) { console.error('usage: digroute-build.js <sim dir> <out dir>'); process.exit(2); }
fs.mkdirSync(outDir, { recursive: true });
cp.execFileSync('node', [path.join(__dirname, 'l0-build.js'), simDir, outDir], { stdio: 'ignore' });   // l0-sim.h: hashes, Msg, Dig
const seat = fs.readFileSync(path.join(simDir, 'mesh_seat.inc'), 'utf8').split('\n');
const mesh = fs.readFileSync(path.join(simDir, 'mesh.cpp'), 'utf8').split('\n');
const find = (a, re, from = 0) => { for (let i = from; i < a.length; i++) if (re.test(a[i])) return i; throw new Error('digroute-build: no line ' + re); };
const cut = (a, from, toRe) => { const i = find(a, from), j = find(a, toRe, i + 1); return a.slice(i, j); };
const parts = [];
parts.push(seat[find(seat, /^static inline Coord unck\(/)]);
parts.push(seat[find(seat, /^static inline bool cellOk\(/)]);
parts.push(...cut(seat, /^static void l12Origin\(/, /^\/\/ No other row of my section/));
for (const re of [/^static uint32_t kHash\(/, /^static bool kSameVote\(/, /^static bool kHasVote\(/, /^static uint64_t kTakerOf\(/]) parts.push(seat[find(seat, re)]);
parts.push(mesh[find(mesh, /^static const long long DIG_TTL=/)]);
parts.push(...cut(seat, /^static void kOver\(/, /^\/\/ THE SECOND UP-EDGE/));
parts.push(...cut(seat, /^static bool kInScope\(/, /^void Seat::kIntake\(/));
{
  const nh = cut(seat, /^bool Seat::nextHopCoord\(/, /^int Seat::nextHopToward\(/);
  nh[0] = nh[0].replace('bool Seat::nextHopCoord(Coord t, Coord& out){', 'static bool nextHopCoordF(Coord c, Coord t, Coord& out){');
  if (nh[1].trim() !== 'Coord c=coord;') throw new Error('digroute-build: nextHopCoord body changed');
  nh.splice(1, 1);
  parts.push(...nh);
}
parts.push(...cut(mesh, /^static string coordStr\(Coord c\)\{/, /^\/\/ --trace <out\.jsonl>/));
fs.writeFileSync(path.join(outDir, 'digroute-sim.h'), '// GENERATED by digroute-build.js from the sim source: do not edit.\n#pragma once\n' + parts.join('\n') + '\n');
const bin = path.join(outDir, 'digroute-driver');
cp.execFileSync('g++', ['-O2', '-std=c++17', '-I', simDir, '-I', outDir, '-o', bin, path.join(__dirname, 'digroute-driver.cpp')], { stdio: 'inherit' });
console.log(bin);
