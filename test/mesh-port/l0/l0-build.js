#!/usr/bin/env node
// l0-build.js <sim dir> <out dir>
// Builds the L0 driver: test/mesh-port/l0/l0-driver.cpp compiled against the sim's own headers (topo.h,
// roles.h, omap.h, laws.h) and the sim's own text for everything else it calls, cut from mesh.cpp:
//   - the hash helpers, the Msg structs and the digest helpers (H_INIT .. votesHold)
//   - grnd / frnd (the fabric LCGs)
//   - Seat::rng and the seed statements of Seat::Seat
// Nothing is retyped: a change in the sim reaches the driver at the next build. Prints the binary's path.
'use strict';
const fs = require('fs'), path = require('path'), cp = require('child_process');

const [simDir, outDir] = process.argv.slice(2);
if (!simDir || !outDir) { console.error('usage: l0-build.js <sim dir> <out dir>'); process.exit(2); }
const src = fs.readFileSync(path.join(simDir, 'mesh.cpp'), 'utf8').split('\n');
const find = (re, from = 0) => { for (let i = from; i < src.length; i++) if (re.test(src[i])) return i; throw new Error('l0-build: no line ' + re); };
const need = (cond, what) => { if (!cond) throw new Error('l0-build: ' + what); };

// 1. hash helpers .. votesHold: from `static const uint32_t H_INIT` to the line before `struct Ent`.
const a = find(/^static const uint32_t H_INIT=/), b = find(/^struct Ent \{/, a);
const core = src.slice(a, b).join('\n');
// 2. the fabric LCGs
const gl = src[find(/^static inline double grnd\(\)/)], fl = src[find(/^static inline double frnd\(\)/)];
// 3. Seat::rng and the constructor's seed statements
const rngLine = src[find(/^\s*inline double rng\(\)\{/)].trim();
const ctor = src[find(/^\s*Seat\(int i\):id\(i\)\{/)];
const seed = /\{\s*(uint32_t h=2166136261u;.*?rs=h\^0x9e3779b9u;)/.exec(ctor);
need(seed, 'seed statements in Seat::Seat');

const hdr = [
  '// GENERATED by l0-build.js from the sim source: do not edit.',
  '#pragma once',
  'static uint32_t GSEED=0, FSEED=0;',
  gl, fl, core,
  '// Seat::rng and the seed of Seat::Seat, as the sim writes them',
  'struct RngSeat { uint32_t rs; RngSeat(int i){ ' + seed[1] + ' }',
  '  ' + rngLine + ' };',
].join('\n') + '\n';
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'l0-sim.h'), hdr);
const bin = path.join(outDir, 'l0-driver');
cp.execFileSync('g++', ['-O2', '-std=c++17', '-I', simDir, '-I', outDir, '-o', bin, path.join(__dirname, 'l0-driver.cpp')], { stdio: 'inherit' });
console.log(bin);
